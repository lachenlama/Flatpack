/**
 * Generates shared/abi/*.ts (typed `as const` ABIs) from Hardhat artifacts, for the keeper (WP4b) and the app (WP5).
 * Run after `npm run build`:  node scripts/export-abis.ts
 * The output is committed. Re-run whenever a contract ABI changes.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifacts = join(here, "..", "artifacts", "src");
const out = join(here, "..", "..", "shared", "abi");

const CONTRACTS: Array<[string, string]> = [
  ["ComponentRegistry.sol/ComponentRegistry.json", "componentRegistryAbi"],
  ["Basket.sol/Basket.json", "basketAbi"],
  ["BasketFactory.sol/BasketFactory.json", "basketFactoryAbi"],
  ["BackingVault.sol/BackingVault.json", "backingVaultAbi"],
  ["FeeHarvester.sol/FeeHarvester.json", "feeHarvesterAbi"],
  ["FlatpackRouter.sol/FlatpackRouter.json", "flatpackRouterAbi"],
  ["interfaces/external/IExternal.sol/IScaledUIAmount.json", "scaledUiAmountAbi"],
  ["interfaces/external/IExternal.sol/IPausableToken.json", "pausableTokenAbi"],
  ["interfaces/external/IExternal.sol/IAggregatorV3.json", "aggregatorV3Abi"],
];

mkdirSync(out, { recursive: true });
const index: string[] = [];
for (const [path, name] of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(join(artifacts, path), "utf8"));
  const file = `${name}.ts`;
  writeFileSync(
    join(out, file),
    `// GENERATED by contracts/scripts/export-abis.ts. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${name} } from "./${file}";`);
}
// ERC-20: use viem's built-in `erc20Abi` (import { erc20Abi } from "viem").
writeFileSync(join(out, "index.ts"), `// GENERATED. Do not edit.\n${index.join("\n")}\n`);
console.log(`wrote ${index.length} ABIs to ${out}`);
